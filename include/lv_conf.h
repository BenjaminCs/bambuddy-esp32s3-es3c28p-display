// LVGL 9 configuration: only the values that differ from LVGL's defaults
// (everything else comes from lv_conf_internal.h).
//
// Keep the LV_CONF_H guard: LVGL checks for it and prints "Possible failure to
// include lv_conf.h" on every file if it is missing (#pragma once is not enough).
#ifndef LV_CONF_H
#define LV_CONF_H

#define LV_COLOR_DEPTH 16

// Use the C library allocator so large allocations can land in PSRAM.
#define LV_USE_STDLIB_MALLOC  LV_STDLIB_CLIB
#define LV_USE_STDLIB_STRING  LV_STDLIB_CLIB
#define LV_USE_STDLIB_SPRINTF LV_STDLIB_CLIB

#define LV_DEF_REFR_PERIOD 20
#define LV_USE_LOG 0

// LVGL's built-in Montserrat only has ASCII, so accented UI text (e.g. Hungarian
// ő/ű) would render as boxes. Custom fonts generated by tools/gen_fonts.sh replace
// it: ASCII + Latin-1 + Őőűű + the LVGL FontAwesome symbols.
#define LV_FONT_MONTSERRAT_14 0
#define LV_FONT_CUSTOM_DECLARE LV_FONT_DECLARE(font_hu_14) LV_FONT_DECLARE(font_hu_18) LV_FONT_DECLARE(font_hu_28)
#define LV_FONT_DEFAULT &font_hu_14

#define LV_USE_THEME_DEFAULT 1
#define LV_THEME_DEFAULT_DARK 1

#endif
